int term_cursor_x = 0;
int term_cursor_y = 0;

unsigned char* backbuffer;

void screen_init(void) {
    screen.framebuffer = (unsigned char*)(framebuffer_addr - 0x20000); 
    screen.width = screen_width;
    screen.height = screen_height;
    screen.pitch = screen_pitch;
    screen.bpp = screen_bpp;
}

void put_pixel(int x, int y, unsigned char r, unsigned char g, unsigned char b) {
    if (x < 0 || y < 0 || x >= screen.width || y >= screen.height) return;

    int bytes_per_pixel = screen.bpp / 8;
    int offset = y * screen.pitch + x * bytes_per_pixel;

    backbuffer[offset]     = b;
    backbuffer[offset + 1] = g;
    backbuffer[offset + 2] = r;
}

void draw_rect(int x, int y, int width, int height, unsigned char r, unsigned char g, unsigned char b) {
    for (int row = y; row < y + height; row++) {
        for (int col = x; col < x + width; col++) {
            put_pixel(col, row, r, g, b);
        }
    }
}

void draw_rect_c(int x, int y, int w, int h, int color_index) {
    draw_rect(x, y, w, h, palette[color_index][0], palette[color_index][1], palette[color_index][2]);
}

void fill_screen(unsigned char r, unsigned char g, unsigned char b) {
    draw_rect(0, 0, screen.width, screen.height, r, g, b);
}

// Define how big you want the text! (2 = 16x16, 3 = 24x24, etc.)
int text_scale = 2; 

void draw_char(int x, int y, char c, unsigned char r, unsigned char g, unsigned char b, int scale) {
    if (c < 32 || c > 126) return;
    int index = c - 32;

    for (int row = 0; row < 8; row++) {
        unsigned char line = font8x8[index][row];
        for (int col = 0; col < 8; col++) {
            // If the font bit is set, draw a square of size 'scale' instead of a single pixel
            if (line & (0x80 >> col)) {
                draw_rect(x + (col * scale), y + (row * scale), scale, scale, r, g, b);
            }
        }
    }
}

void print_char(char c) {
    // The total width/height of a character is now 8 * scale
    int char_size = 8 * text_scale; 

    if (c == '\n') {
        term_cursor_x = 0;
        term_cursor_y += char_size; 
    } 
    else if (c == '\b') {
        if (term_cursor_x >= char_size) term_cursor_x -= char_size;
        // Erase using a rectangle that matches the scaled character size
        draw_rect(term_cursor_x, term_cursor_y, char_size, char_size, 0x10, 0x10, 0x10); 
    } 
    else {
        // Draw the character scaled up
        draw_char(term_cursor_x, term_cursor_y, c, 0xFF, 0xFF, 0xFF, text_scale);
        term_cursor_x += char_size;

        // Wrap text to the next line if it exceeds screen width
        if (term_cursor_x + char_size > screen.width) {
            term_cursor_x = 0;
            term_cursor_y += char_size;
        }
    }

    // Clear screen if we hit the bottom
    if (term_cursor_y + char_size > screen.height) {
        term_cursor_y = 0;
        fill_screen(0x10, 0x10, 0x10); 
    }
}

void draw_status_bar(void) {
    const int bar_height = 18;
    const int border = 4;
    const unsigned char black_r = palette[COLOR_BLACK][0];
    const unsigned char black_g = palette[COLOR_BLACK][1];
    const unsigned char black_b = palette[COLOR_BLACK][2];
    const unsigned char grass_r = palette[COLOR_GRASSGREEN][0];
    const unsigned char grass_g = palette[COLOR_GRASSGREEN][1];
    const unsigned char grass_b = palette[COLOR_GRASSGREEN][2];

    draw_rect(0, 0, screen.width, bar_height, black_r, black_g, black_b);
    draw_rect(0, screen.height - bar_height, screen.width, bar_height, black_r, black_g, black_b);

    draw_rect(0, screen.height - border, screen.width, border, grass_r, grass_g, grass_b);
    draw_rect(0, 0, border, screen.height, grass_r, grass_g, grass_b);
    draw_rect(screen.width - border, 0, border, screen.height, grass_r, grass_g, grass_b);
}

void draw_text_line(int x, int y, const char* text) {
    for (int idx = 0; text[idx] != '\0'; idx++) {
        draw_char(x + (idx * 8), y, text[idx], 0xFF, 0xFF, 0xFF, 1);
    }
}

void clear_status_text_area(void) {
    draw_rect(0, 0, screen.width, 18, 0x00, 0x00, 0x00);
    draw_status_bar();
}

void draw_status_text(void) {
    unsigned int uptime = timer_get_uptime_seconds();
    unsigned int cpu = timer_get_cpu_usage_percent();
    unsigned int hours = uptime / 3600;
    unsigned int minutes = (uptime / 60) % 60;
    unsigned int seconds = uptime % 60;
    char buffer[32];
    char cpu_buffer[16];
    char clock_buffer[16];
    int pos = 0;

    buffer[pos++] = 'U';
    buffer[pos++] = 'P';
    buffer[pos++] = ':';
    buffer[pos++] = ' ';
    buffer[pos++] = '0' + (hours / 10);
    buffer[pos++] = '0' + (hours % 10);
    buffer[pos++] = 'h';
    buffer[pos++] = ' ';
    buffer[pos++] = '0' + (minutes / 10);
    buffer[pos++] = '0' + (minutes % 10);
    buffer[pos++] = 'm';
    buffer[pos++] = ' ';
    buffer[pos++] = '0' + (seconds / 10);
    buffer[pos++] = '0' + (seconds % 10);
    buffer[pos++] = 's';
    buffer[pos] = '\0';

    clear_status_text_area();
    draw_text_line(8, 4, buffer);

    pos = 0;
    cpu_buffer[pos++] = 'C';
    cpu_buffer[pos++] = 'P';
    cpu_buffer[pos++] = 'U';
    cpu_buffer[pos++] = ':';
    cpu_buffer[pos++] = ' ';
    cpu_buffer[pos++] = '0' + (cpu / 100);
    cpu_buffer[pos++] = '0' + ((cpu / 10) % 10);
    cpu_buffer[pos++] = '0' + (cpu % 10);
    cpu_buffer[pos++] = '%';
    cpu_buffer[pos] = '\0';

    draw_text_line(220, 4, cpu_buffer);

    // --- clock, top-right ---
    struct rtc_time now;
    int rtc_valid = rtc_read(&now);

    pos = 0;
    if (rtc_valid) {
        clock_buffer[pos++] = '0' + (now.hours / 10);
        clock_buffer[pos++] = '0' + (now.hours % 10);
        clock_buffer[pos++] = ':';
        clock_buffer[pos++] = '0' + (now.minutes / 10);
        clock_buffer[pos++] = ':';
        clock_buffer[pos++] = '0' + (now.seconds / 10);
        clock_buffer[pos++] = '0' + (now.seconds % 10);
    } else {
        clock_buffer[pos++] = '-';
        clock_buffer[pos++] = '-';
        clock_buffer[pos++] = ':';
        clock_buffer[pos++] = '-';
        clock_buffer[pos++] = '-';
        clock_buffer[pos++] = ':';
        clock_buffer[pos++] = '-';
        clock_buffer[pos++] = '-';
    }
    clock_buffer[pos] = '\0';

    // right-align: screen width minus (8 chars * ~9px per char) minus a small margin
    int clock_x = screen.width - (8 * 9) - 8;
    draw_text_line(clock_x, 4, clock_buffer);
}

void render_status_frame(void) {
    static unsigned int last_render_tick = 0;
    static unsigned int last_uptime = 0;
    static unsigned int last_cpu = 0;
    unsigned int current_tick = timer_get_ticks();
    unsigned int uptime = timer_get_uptime_seconds();
    unsigned int cpu = timer_get_cpu_usage_percent();

    if (last_render_tick == 0) {
        draw_status_bar();
        draw_status_text();
        last_render_tick = current_tick;
        last_uptime = uptime;
        last_cpu = cpu;
        return;
    }

    if (current_tick - last_render_tick < 100) {
        return;
    }

    if (uptime != last_uptime || cpu != last_cpu) {
        draw_status_text();
        last_uptime = uptime;
        last_cpu = cpu;
    }

    last_render_tick = current_tick;
}

unsigned char* backbuffer;

void backbuffer_init(void) {
    unsigned int buffer_size = screen.pitch * screen.height;
    backbuffer = (unsigned char*)kmalloc(buffer_size);
}


void screen_swap(void) {
    unsigned int buffer_size = screen.pitch * screen.height;
    unsigned int dword_count = buffer_size / 4;

    fast_copy(screen.framebuffer, backbuffer, dword_count);

    // handle any leftover bytes if buffer_size isn't evenly divisible by 4
    unsigned int remainder = buffer_size % 4;
    if (remainder) {
        unsigned char* dst = screen.framebuffer + (dword_count * 4);
        unsigned char* src = backbuffer + (dword_count * 4);
        for (unsigned int i = 0; i < remainder; i++) {
            dst[i] = src[i];
        }
    }
}