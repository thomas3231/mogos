int term_cursor_x = 0;
int term_cursor_y = 0;

void screen_init(void) {
    screen.framebuffer = (unsigned char*)(framebuffer_addr - 0x20000); 
    screen.width = screen_width;
    screen.height = screen_height;
    screen.pitch = screen_pitch;
    screen.bpp = screen_bpp;
}

void put_pixel(int x, int y, unsigned char r, unsigned char g, unsigned char b) {
    if (x < 0 || y < 0 || x >= screen.width || y >= screen.height) return;

    int bytes_per_pixel = screen.bpp / 8;
    int offset = (y * screen.pitch) + (x * bytes_per_pixel);

    screen.framebuffer[offset]     = b; 
    screen.framebuffer[offset + 1] = g; 
    screen.framebuffer[offset + 2] = r; 
}

void draw_rect(int x, int y, int width, int height, unsigned char r, unsigned char g, unsigned char b) {
    for (int row = y; row < y + height; row++) {
        for (int col = x; col < x + width; col++) {
            put_pixel(col, row, r, g, b);
        }
    }
}

void draw_rect_c(int x, int y, int w, int h, int color_index) {
    draw_rect(x, y, w, h, palette[color_index][0], palette[color_index][1], palette[color_index][2]);
}

void fill_screen(unsigned char r, unsigned char g, unsigned char b) {
    draw_rect(0, 0, screen.width, screen.height, r, g, b);
}

// Define how big you want the text! (2 = 16x16, 3 = 24x24, etc.)
int text_scale = 2; 

void draw_char(int x, int y, char c, unsigned char r, unsigned char g, unsigned char b, int scale) {
    if (c < 32 || c > 126) return;
    int index = c - 32;

    for (int row = 0; row < 8; row++) {
        unsigned char line = font8x8[index][row];
        for (int col = 0; col < 8; col++) {
            // If the font bit is set, draw a square of size 'scale' instead of a single pixel
            if (line & (0x80 >> col)) {
                draw_rect(x + (col * scale), y + (row * scale), scale, scale, r, g, b);
            }
        }
    }
}

void print_char(char c) {
    // The total width/height of a character is now 8 * scale
    int char_size = 8 * text_scale; 

    if (c == '\n') {
        term_cursor_x = 0;
        term_cursor_y += char_size; 
    } 
    else if (c == '\b') {
        if (term_cursor_x >= char_size) term_cursor_x -= char_size;
        // Erase using a rectangle that matches the scaled character size
        draw_rect(term_cursor_x, term_cursor_y, char_size, char_size, 0x10, 0x10, 0x10); 
    } 
    else {
        // Draw the character scaled up
        draw_char(term_cursor_x, term_cursor_y, c, 0xFF, 0xFF, 0xFF, text_scale);
        term_cursor_x += char_size;

        // Wrap text to the next line if it exceeds screen width
        if (term_cursor_x + char_size > screen.width) {
            term_cursor_x = 0;
            term_cursor_y += char_size;
        }
    }

    // Clear screen if we hit the bottom
    if (term_cursor_y + char_size > screen.height) {
        term_cursor_y = 0;
        fill_screen(0x10, 0x10, 0x10); 
    }
}